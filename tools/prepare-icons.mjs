import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
// Keep the exact icon/font mapping shipped by the locked uview-plus dependency.
const source = "node_modules/uview-plus/components/u-icon/upicon.ttf";
const dataUrl = `data:font/ttf;base64,${(await readFile(source)).toString("base64")}`;
await mkdir("src/generated", { recursive: true });
await mkdir("src/static/app-plus/uview-plus", { recursive: true });
await writeFile(
  "src/generated/icons.ts",
  `// Generated by tools/prepare-icons.mjs.\nexport const iconFontUrl = ${JSON.stringify(dataUrl)};\n`,
);
await writeFile(
  "src/generated/icons.scss",
  `/* Generated from uview-plus, MIT. Embedded for H5 and mini-program offline rendering. */\n@font-face { font-family: 'uicon-iconfont'; src: url('${dataUrl}') format('truetype'); }\n`,
);
await copyFile(source, "src/static/app-plus/uview-plus/upicon.ttf");
await copyFile(
  "node_modules/uview-plus/LICENSE",
  "src/static/app-plus/uview-plus/LICENSE.txt",
);
